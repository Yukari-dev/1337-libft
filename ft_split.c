#include "libft.h"

static char	**free_array(char **arr, size_t index)
{
	while (index > 0)
		free(arr[--index]);
	free(arr);
	return (NULL);
}

static size_t	get_word_len(char const *s, char c)
{
	size_t	len;

	len = 0;
	while (s[len] && s[len] != c)
		len++;
	return (len);
}

static size_t	countchar(char const *s, char c)
{
	size_t	count;

	count = 0;
	while (*s)
	{
		while (*s && *s == c)
			s++;
		if (*s)
			count++;
		while (*s && *s != c)
			s++;
	}
	return (count);
}

static char	*strduplicate(const char *src, size_t len)
{
	char	*word;
	size_t	i;

	word = malloc(sizeof(char) * (len + 1));
	if (!word)
		return (NULL);
	i = 0;
	while (i < len)
	{
		word[i] = src[i];
		i++;
	}
	word[i] = '\0';
	return (word);
}

char	**ft_split(char const *s, char c)
{
	char	**arr;
	size_t	i;
	size_t	len;

	if (!s)
		return (NULL);
	arr = malloc(sizeof(char *) * (countchar(s, c) + 1));
	if (!arr)
		return (NULL);
	i = 0;
	while (*s)
	{
		while (*s && *s == c)
			s++;
		if (!*s)
			break ;
		len = get_word_len(s, c);
		arr[i] = strduplicate(s, len);
		if (!arr[i])
			return (free_array(arr, i));
		i++;
		s += len;
	}
	arr[i] = NULL;
	return (arr);
}
