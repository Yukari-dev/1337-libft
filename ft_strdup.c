#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*ret;
	size_t	i;

	i = 0;
	while (s[i])
		i++;
	ret = (char *)malloc(i + 1);
	if (!ret)
		return (NULL);
	i = 0;
	while (s[i])
	{
		ret[i] = s[i];
		i++;
	}
	ret[i] = '\0';
	return (ret);
}
