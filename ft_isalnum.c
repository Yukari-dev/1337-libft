static int	ft_alpha(int c)
{
	if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'))
		return (1);
	return (0);
}

int	ft_isalnum(int c)
{
	if (ft_alpha(c) || (c >= '0' && c <= '9'))
		return (1);
	return (0);
}
